// A copy of a rule in the same project, off, named "Copy of …" (webhook URLs and secrets stay stored
// out of reach: the database clones a copied reference within the project). Answers the copy's id.
export async function duplicateRule(ctx: ApiContext, ruleId: string): Promise<string | undefined> {
  const supabase = ctx.db;
  const source = await supabase
    .from("rules")
    .select("project_id, name, trigger_type, trigger_config, conditions, actions, sort_order")
    .eq("id", id(ruleId, "rule"))
    .is("deleted_at", null)
    .maybeSingle();
  check(source);
  if (!source.data) throw invalid("Automation not found");
  const inserted = await supabase
    .from("rules")
    .insert({
      project_id: source.data.project_id,
      name: `Copy of ${source.data.name}`.slice(0, 200),
      enabled: false,
      trigger_type: source.data.trigger_type,
      trigger_config: source.data.trigger_config,
      conditions: source.data.conditions,
      actions: source.data.actions,
      sort_order: source.data.sort_order + 1,
    })
    .select("id")
    .single();
  check(inserted, "Only project admins and owners change its automations");
  return inserted.data?.id;
}

// Pause a rule until a time (null = resume now).
export async function setRulePausedUntil(ctx: ApiContext, ruleId: string, until: string | null): Promise<void> {
  const supabase = ctx.db;
  const updated = await supabase.from("rules").update({ paused_until: pauseUntil(until) }).eq("id", id(ruleId, "rule")).select("id");
  if (updated.error?.code === "PGRST204" || updated.error?.code === "42703") throw invalid(RULES_V3_MISSING);
  checkUpdated(updated, "Only project admins and owners change its automations");
}
