// Admin+ (set_project_integration). An empty value clears the setting. Values are never echoed back.
export async function setProjectIntegration(
  ctx: ApiContext,
  projectId: string,
  setting: string,
  value: string,
): Promise<{ settings: ProjectIntegrations }> {
  if (!isIntegrationSetting(setting)) throw invalid("Unknown integration setting");
  const trimmed = typeof value === "string" ? value.trim() : "";
  if ((setting === "slack_webhook_url" || setting === "webhook_url") && trimmed && !isAllowedWebhookUrl(trimmed)) {
    throw invalid(WEBHOOK_URL_ERROR);
  }
  if (setting === "webhook_secret" && trimmed.length > MAX_SECRET_LENGTH) {
    throw invalid("The shared secret is limited to 500 characters");
  }
  if (setting === "webhook_secret_header" && trimmed && !isAllowedHeaderName(trimmed)) {
    throw invalid("Header names use letters, digits, and dashes (and can’t be a standard transport header)");
  }
  const supabase = ctx.db;
  const response = await supabase.rpc("set_project_integration", {
    target_project: id(projectId),
    setting,
    new_value: trimmed || null,
  });
  check(response);
  return { settings: toProjectIntegrations(response.data) };
}

// Admin+: a new project signing secret for Call webhook requests to the project URL. The caller generates
// it (the adapter: node:crypto lives in the server-only integrations module) and this returns it once so
// the admin can copy it into the receiver; the database never hands it back.
export async function generateProjectSigningSecret(
  ctx: ApiContext,
  projectId: string,
  generated: string,
): Promise<{ secret: string; settings: ProjectIntegrations }> {
  const supabase = ctx.db;
  const response = await supabase.rpc("set_project_integration", {
    target_project: id(projectId),
    setting: "signing_secret",
    new_value: generated,
  });
  check(response);
  return { secret: generated, settings: toProjectIntegrations(response.data) };
}

