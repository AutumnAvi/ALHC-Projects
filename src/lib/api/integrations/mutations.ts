// ---------------------------------------------------------------------------------------------
// Delivery log (Admin+ of the delivery's project; the RPCs check). A retry is sent right after the
// response (the adapter's), reusing the stored payload; cancel stops a delivery that is still waiting.
// ---------------------------------------------------------------------------------------------

export async function retryIntegrationDelivery(ctx: ApiContext, deliveryId: string): Promise<void> {
  const supabase = ctx.db;
  check(await supabase.rpc("retry_integration_delivery", { target_delivery: id(deliveryId) }));
}

