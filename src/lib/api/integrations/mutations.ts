// Big move 1: the integrations area's writes (Slack / webhook settings and signing secrets, inbound
// webhook endpoints, the delivery log). Every function takes the caller's ApiContext first, validates its
// own input, writes only through ctx.db (RLS and the RPCs decide), and throws ApiError on any refusal; no
// Next.js here. Delivering a retried row after the response is the adapter's.
import type { ApiContext } from "@/lib/api/core/context";
import { check, checkUpdated, nowIso } from "@/lib/api/core/db";
import { invalid } from "@/lib/api/core/errors";
import { id, text } from "@/lib/api/core/validate";
import type { InboundEndpointInput } from "@/lib/api/integrations/model";
import {
  MAX_SECRET_LENGTH,
  WEBHOOK_URL_ERROR,
  isAllowedHeaderName,
  isAllowedWebhookUrl,
  isIntegrationSetting,
  toProjectIntegrations,
  type ProjectIntegrations,
} from "@/lib/integrations-shared";
import type { TablesUpdate } from "@/lib/supabase/database.types";

