"use server";
// Big move 1: integrations (Slack / webhook settings, signing secrets), inbound webhook endpoints, and the
// delivery log — thin Server Action wrappers around src/lib/api/integrations/mutations.ts. Generating a
// signing secret and delivering a retried row after the response stay here (server-only work).
import { after } from "next/server";
import type { ActionResult } from "@/lib/api/core/result";
import type { InboundEndpointInput } from "@/lib/api/integrations/model";
import * as integrationsApi from "@/lib/api/integrations/mutations";
import { drainIntegrationOutbox, generateSigningSecret } from "@/lib/integrations";
import type { ProjectIntegrations } from "@/lib/integrations-shared";
import { run, runWith } from "@/lib/server/action";

// ---------------------------------------------------------------------------------------------
// Project integration settings
// ---------------------------------------------------------------------------------------------

// Admin+ (set_project_integration). An empty value clears the setting. Values are never echoed back.
export async function setProjectIntegration(
  projectId: string,
  setting: string,
  value: string,
): Promise<ActionResult & { settings?: ProjectIntegrations }> {
  return runWith((ctx) => integrationsApi.setProjectIntegration(ctx, projectId, setting, value));
}

// Admin+: a new project signing secret for Call webhook requests to the project URL. Generated here and
// returned once so the admin can copy it into the receiver; the database never hands it back.
export async function generateProjectSigningSecret(
  projectId: string,
): Promise<ActionResult & { secret?: string; settings?: ProjectIntegrations }> {
  return runWith((ctx) => integrationsApi.generateProjectSigningSecret(ctx, projectId, generateSigningSecret()));
}

export async function clearProjectSigningSecret(
  projectId: string,
): Promise<ActionResult & { settings?: ProjectIntegrations }> {
  return runWith((ctx) => integrationsApi.clearProjectSigningSecret(ctx, projectId));
}

// ---------------------------------------------------------------------------------------------
