-- One feed's events (the public /api/calendar/<token>.ics route, anon only). A token in; out comes
-- { ok, status, name, events } where status is
--   unknown       not a live token we know (malformed, never made, or replaced by a newer one): the route
--                 answers 404 and says nothing more;
--   off           the link was turned off, or its owner is no longer in the workspace: an empty calendar,
--                 so subscribed calendars drop the old events;
--   rate_limited  more than 60 fetches in the last hour: 429, the calendar app keeps what it has;
--   ok            the events, built with the owner's own access right now: request.jwt.claim.sub is set to
--                 them locally (restored before returning), so has_task_role / has_project_role answer
--                 exactly as for them signed in. My tasks = open tasks assigned to them with a date (and
--                 ones completed in the last 90 days), private tasks included because they can read them;
--                 a project = its tasks while they can open it; a team = tasks in the team's projects
--                 they are a member of (the team Calendar's rule). Top-level tasks only for projects and
--                 teams (subtasks have no project rows), at most 3,000 events, nearest to today first.
-- Each event: task id, title, dates (and times when set), completed, kind, project name, a link path.
-- Never notes, comments, attachments, or field values.
create or replace function public.calendar_feed(feed_token text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  token text := btrim(coalesce(feed_token, ''));
  f public.calendar_feeds;
  owner_name text;
  feed_name text;
  previous_sub text := current_setting('request.jwt.claim.sub', true);
  today date := (now() at time zone 'UTC')::date;
  events jsonb := '[]'::jsonb;
  max_events constant integer := 3000;
begin
  if token !~ '^alhc_cal_[0-9a-f]{64}$' then
    return jsonb_build_object('ok', false, 'status', 'unknown');
  end if;
  select * into f from public.calendar_feeds c
  where c.token_hash = public.inbound_token_hash(token)
  for update;
  if not found then
    return jsonb_build_object('ok', false, 'status', 'unknown');
  end if;
  if f.revoked_at is not null or not public.profile_is_allowlisted(f.profile_id) then
    return jsonb_build_object('ok', true, 'status', 'off', 'name', 'ALHC Projects', 'events', '[]'::jsonb);
  end if;

  -- 60 fetches an hour per link (calendar apps poll every 15 minutes to a day).
  if f.fetch_window_started_at is null or f.fetch_window_started_at < now() - interval '1 hour' then
    update public.calendar_feeds
    set fetch_window_started_at = now(), fetch_count = 1, last_fetched_at = now()
    where id = f.id;
  elsif f.fetch_count >= 60 then
    return jsonb_build_object('ok', false, 'status', 'rate_limited');
  else
    update public.calendar_feeds
    set fetch_count = f.fetch_count + 1, last_fetched_at = now()
    where id = f.id;
  end if;

  perform set_config('request.jwt.claim.sub', f.profile_id::text, true);

  if f.scope = 'my_tasks' then
    select coalesce(nullif(btrim(p.full_name), ''), split_part(p.email, '@', 1)) into owner_name
    from public.profiles p where p.id = f.profile_id;
    feed_name := 'My tasks' || coalesce(' — ' || owner_name, '');
    select coalesce(jsonb_agg(x.event order by x.distance, x.id), '[]'::jsonb) into events
    from (
      select t.id, abs(coalesce(t.due_on, t.start_on) - today) as distance,
             jsonb_build_object(
               'id', t.id, 'title', t.title, 'start_on', t.start_on, 'due_on', t.due_on,
               'start_at', t.start_at, 'due_at', t.due_at, 'completed', t.completed_at is not null,
               'kind', t.kind, 'updated_at', t.updated_at,
               'project', pr.name,
               'path', case
                 when pr.id is null then '/my-tasks?task=' || t.id
                 else '/projects/' || pr.id || '?task=' || t.id
               end
             ) as event
      from public.tasks t
      left join lateral (
        select x.id, x.name from public.projects x
        where x.id = public.comment_email_project(f.profile_id, t.id)
      ) pr on true
      where t.assignee_id = f.profile_id
        and t.deleted_at is null
        and (t.due_on is not null or t.start_on is not null)
        and (t.completed_at is null or t.completed_at > now() - interval '90 days')
        and public.has_task_role(t.id, 'viewer')
      order by abs(coalesce(t.due_on, t.start_on) - today), t.id
      limit max_events
    ) x;
  else
    if f.scope = 'project' then
      select pr.name into feed_name from public.projects pr
      where pr.id = f.project_id and pr.deleted_at is null and public.has_project_role(pr.id, 'viewer');
    else
      select te.name into feed_name from public.teams te
      where te.id = f.team_id and public.can_read_team(te.id);
    end if;
    if feed_name is not null then
      select coalesce(jsonb_agg(x.event order by x.distance, x.id), '[]'::jsonb) into events
      from (
        select distinct on (abs(coalesce(t.due_on, t.start_on) - today), t.id)
               t.id, abs(coalesce(t.due_on, t.start_on) - today) as distance,
               jsonb_build_object(
                 'id', t.id, 'title', t.title, 'start_on', t.start_on, 'due_on', t.due_on,
                 'start_at', t.start_at, 'due_at', t.due_at, 'completed', t.completed_at is not null,
                 'kind', t.kind, 'updated_at', t.updated_at,
                 'project', pr.name,
                 'path', '/projects/' || pr.id || '?task=' || t.id
               ) as event
        from public.projects pr
        join public.task_projects tp on tp.project_id = pr.id and tp.deleted_at is null
        join public.tasks t on t.id = tp.task_id
        where pr.deleted_at is null
          and (
            (f.scope = 'project' and pr.id = f.project_id)
            or (f.scope = 'team' and pr.team_id = f.team_id and exists (
              select 1 from public.project_members m
              where m.project_id = pr.id and m.profile_id = f.profile_id and m.deleted_at is null
            ))
          )
          and public.has_project_role(pr.id, 'viewer')
          and t.deleted_at is null
          and (t.due_on is not null or t.start_on is not null)
          and (t.completed_at is null or t.completed_at > now() - interval '90 days')
        order by abs(coalesce(t.due_on, t.start_on) - today), t.id, (pr.id = t.home_project_id) desc, pr.name
        limit max_events
      ) x;
    else
      feed_name := 'ALHC Projects';
    end if;
  end if;

  perform set_config('request.jwt.claim.sub', coalesce(previous_sub, ''), true);
  return jsonb_build_object('ok', true, 'status', 'ok', 'name', feed_name, 'scope', f.scope, 'events', events);
end;
$$;

