-- Invoker guard: the owner is the caller; a feed names a project / team the caller can open when it's
-- made; only token_rotated_at (rotate) and revoked_at (turn off, final) change afterwards. On insert and
-- on every rotation it generates a new token, stores its hash and hint, resets the fetch counter, and
-- hands the plain token back once through the transaction-local setting alhc.calendar_feed_token (read
-- and cleared by the RPCs below). A client never chooses a token: token_hash isn't grantable.
create or replace function public.guard_calendar_feed()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  token text;
begin
  if tg_op = 'INSERT' then
    if public.is_client_role() then
      new.profile_id := auth.uid();
      new.created_at := now();
    end if;
    new.revoked_at := null;
    new.last_fetched_at := null;
    if new.scope = 'project' and not public.has_project_role(new.project_id, 'viewer') then
      raise exception 'Project not found' using errcode = 'no_data_found';
    end if;
    if new.scope = 'team' and not public.can_read_team(new.team_id) then
      raise exception 'Team not found' using errcode = 'no_data_found';
    end if;
  else
    if new.profile_id <> old.profile_id or new.scope <> old.scope
       or new.project_id is distinct from old.project_id or new.team_id is distinct from old.team_id
       or new.created_at <> old.created_at then
      raise exception 'A calendar link can''t move' using errcode = 'insufficient_privilege';
    end if;
    if old.revoked_at is not null then
      raise exception 'This calendar link was turned off' using errcode = 'check_violation';
    end if;
    if new.revoked_at is not null then
      new.revoked_at := now();
    end if;
  end if;

  if tg_op = 'INSERT' or (new.token_rotated_at is distinct from old.token_rotated_at and new.revoked_at is null) then
    token := 'alhc_cal_' || public.inbound_random_hex();
    new.token_hash := public.inbound_token_hash(token);
    new.token_hint := '…' || right(token, 4);
    new.token_rotated_at := clock_timestamp();
    new.fetch_count := 0;
    new.fetch_window_started_at := null;
    new.last_fetched_at := null;
    perform set_config('alhc.calendar_feed_token', token, true);
  else
    new.token_hash := old.token_hash;
    new.token_hint := old.token_hint;
    new.token_rotated_at := old.token_rotated_at;
    if public.is_client_role() then
      new.fetch_count := old.fetch_count;
      new.fetch_window_started_at := old.fetch_window_started_at;
      new.last_fetched_at := old.last_fetched_at;
    end if;
  end if;
  return new;
end;
$$;

