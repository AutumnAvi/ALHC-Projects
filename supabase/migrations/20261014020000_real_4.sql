-- ALHC Projects — Phase: Real features 4 (data and calendar).
-- ROADMAP.md section 0 still listed a read-only team Calendar, no iCal feed, a CSV export capped at
-- 10,000 rows, and an empty "Status templates" card. The calendar drag and the streamed export are app
-- code on existing paths (updateTask / the dependency shift RPCs, and the same access-checked reads);
-- this migration adds only what they and the two new features need:
--
--   Status templates. project_status_templates (per project, like task templates): a name, a default
--     status, a default title, and section headings with body text that prefill a new status update.
--     Read by the project's Viewers+, created and managed by its Editors+ (the people who can post a
--     status update), soft delete, validated by an invoker guard. No function: plain RLS.
--   Calendar feeds (iCal). calendar_feeds (own rows only): one subscribe link per person and feed — My
--     tasks, a project, or a team. The token is generated by the database (an invoker guard, like inbound
--     webhook tokens), handed back once through a transaction-local setting by the invoker RPCs
--     create_calendar_feed / rotate_calendar_feed, and stored only as a SHA-256 hash with a short hint.
--     Revoking sets revoked_at (final). The public route /api/calendar/<token>.ics reads a feed through
--     calendar_feed(token) — the one new anon-callable function (pinned in suites 50, 60, zz06, zz07):
--     a token in, that feed's events out, built with the token owner's own access at every fetch
--     (request.jwt.claim.sub set locally, so has_task_role / has_project_role decide exactly as for them
--     signed in), at most 60 fetches an hour per feed, an empty calendar once the link is turned off or
--     its owner left the workspace. Events carry a task's title, dates (times when set), completed state,
--     project name, and a link path — never notes, comments, or anyone else's tasks. Workspace admins get
--     nothing extra (no function here consults is_workspace_admin()).
--   Streaming CSV export helpers (invoker): filter_project_task_ids() returns a view's matching task ids as
--     one array (PostgREST caps row results at max_rows, so the export can't page a set-returning filter
--     cheaply), and report_overdue_tasks_after() pages the overdue report with a keyset cursor in its own
--     order, 5,000 rows a page as one JSON array (the old function caps at 10,000 and stays for the Reports
--     page and the report emails).
--
-- New client surface: one SECURITY DEFINER function for anon (calendar_feed); nothing new for
-- authenticated in suite 60's definer list (create_calendar_feed, rotate_calendar_feed, the guards, and the
-- export helpers are invoker). fire_rules, notify_with, notify_message, and add_story are untouched.
-- Additive: the release still on main never reads the new tables or functions. No tail.
--
-- The grant on project_status_templates is the last statement: the app treats this release's database
-- features as present once that table is readable.

