-- Make (or, when the caller already has a live link for that feed, replace) a subscribe link. Returns
-- { id, token } — the only time the token is ever shown. Invoker: RLS and the guard decide.
create or replace function public.create_calendar_feed(feed_scope text, target uuid default null)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  feed_id uuid;
  token text;
begin
  if feed_scope is null or feed_scope not in ('my_tasks', 'project', 'team') then
    raise exception 'Choose My tasks, a project, or a team' using errcode = 'check_violation';
  end if;
  if (feed_scope = 'my_tasks') <> (target is null) then
    raise exception 'Choose a project or team for this calendar' using errcode = 'check_violation';
  end if;
  perform set_config('alhc.calendar_feed_token', '', true);
  select f.id into feed_id from public.calendar_feeds f
  where f.profile_id = auth.uid() and f.scope = feed_scope and f.revoked_at is null
    and coalesce(f.project_id, f.team_id) is not distinct from target
  for update;
  if found then
    update public.calendar_feeds set token_rotated_at = clock_timestamp() where id = feed_id;
  else
    insert into public.calendar_feeds (scope, project_id, team_id)
    values (
      feed_scope,
      case when feed_scope = 'project' then target end,
      case when feed_scope = 'team' then target end
    )
    returning id into feed_id;
  end if;
  token := nullif(current_setting('alhc.calendar_feed_token', true), '');
  perform set_config('alhc.calendar_feed_token', '', true);
  if token is null then
    raise exception 'Calendar link not created' using errcode = 'insufficient_privilege';
  end if;
  return jsonb_build_object('id', feed_id, 'token', token);
end;
$$;

revoke all on function public.create_calendar_feed(text, uuid) from public, anon;
grant execute on function public.create_calendar_feed(text, uuid) to authenticated;

-- A new token for one of the caller's live links (the old one stops working at once). Returns { token }.
create or replace function public.rotate_calendar_feed(target_feed uuid)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  token text;
