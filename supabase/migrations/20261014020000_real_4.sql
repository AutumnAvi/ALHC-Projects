-- The overdue report a page at a time for the CSV export: the rows report_overdue_tasks() would return,
-- in its order (due date, title, task id), after the given cursor (null = from the start), up to 5,000 a
-- page, as one JSON array (a row result would be cut at PostgREST's max_rows, and every page re-reads the
-- report, so pages are large). No overall limit: the export asks again until a page comes back short.
create or replace function public.report_overdue_tasks_after(
  filters jsonb default '{}'::jsonb,
  tz text default 'UTC',
  after_due date default null,
  after_title text default null,
  after_task uuid default null,
  max_results integer default 5000
)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  with params as (
    select (now() at time zone public.safe_timezone(tz))::date as today
  ),
  overdue as (
    select distinct on (r.task_id) r.task_id, r.project_id, r.assignee_id, r.due_on
    from public.report_task_rows(filters, tz) r
    join public.tasks t on t.id = r.task_id
    cross join params p
    where r.completed_at is null and r.due_on < p.today
    order by r.task_id, (r.project_id = coalesce(t.home_project_id, r.project_id)) desc, r.project_id
  ),
  page as (
    select o.task_id, t.title, o.project_id, o.assignee_id, o.due_on, (p.today - o.due_on)::integer as days_overdue,
           t.parent_task_id
    from overdue o
    join public.tasks t on t.id = o.task_id
    cross join params p
    where after_task is null or (o.due_on, t.title, o.task_id) > (after_due, after_title, after_task)
    order by o.due_on, t.title, o.task_id
    limit greatest(1, least(coalesce(max_results, 5000), 5000))
  )
  select coalesce(jsonb_agg(to_jsonb(page) order by page.due_on, page.title, page.task_id), '[]'::jsonb) from page;
$$;

revoke all on function public.report_overdue_tasks_after(jsonb, text, date, text, uuid, integer) from public, anon;
grant execute on function public.report_overdue_tasks_after(jsonb, text, date, text, uuid, integer) to authenticated;

