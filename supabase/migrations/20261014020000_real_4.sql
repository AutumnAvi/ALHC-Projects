-- The summary a template's sections make (each heading on its own line, its body under it, a blank line
-- between sections): what the status panel prefills, so it must fit a status update's 2,000 characters.
-- Mirrored by renderStatusTemplate() in src/lib/status-templates.ts.
create or replace function public.status_template_summary(sections jsonb)
returns text
language sql
immutable
set search_path = ''
as $$
  select coalesce(string_agg(
    concat_ws(e'\n', nullif(btrim(s.value ->> 'heading'), ''), nullif(btrim(s.value ->> 'body'), '')),
    e'\n\n' order by s.ordinality
  ), '')
  from jsonb_array_elements(case when jsonb_typeof(sections) = 'array' then sections else '[]'::jsonb end)
    with ordinality s;
$$;

