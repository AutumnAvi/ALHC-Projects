grant execute on function public.status_template_summary(jsonb) to authenticated;

-- Invoker guard: the creator and creation time are the caller's, a template never moves to another
-- project, a removed template stays removed, at most 50 live templates per project, and sections is a
-- list of up to 8 { heading (1–100), body (≤ 1,000) } objects whose summary fits 2,000 characters.
create or replace function public.guard_project_status_template()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  s jsonb;
  cleaned jsonb := '[]'::jsonb;
begin
  if tg_op = 'INSERT' then
    if public.is_client_role() then
      new.created_by := auth.uid();
      new.created_at := now();
    end if;
    new.deleted_at := null;
    if (
      select count(*) from public.project_status_templates t
      where t.project_id = new.project_id and t.deleted_at is null
    ) >= 50 then
      raise exception 'A project can have up to 50 status templates' using errcode = 'check_violation';
    end if;
  else
    if new.project_id <> old.project_id or new.created_by <> old.created_by or new.created_at <> old.created_at then
      raise exception 'A status template can''t move' using errcode = 'insufficient_privilege';
    end if;
    if old.deleted_at is not null then
      raise exception 'This status template was removed' using errcode = 'check_violation';
    end if;
    if new.deleted_at is not null then
      new.deleted_at := now();
    end if;
  end if;

  new.name := btrim(new.name);
  new.title := nullif(btrim(coalesce(new.title, '')), '');
  if jsonb_typeof(new.sections) <> 'array' or jsonb_array_length(new.sections) > 8 then
    raise exception 'A status template has up to 8 sections' using errcode = 'check_violation';
  end if;
  for s in select value from jsonb_array_elements(new.sections) loop
    if jsonb_typeof(s) <> 'object'
       or exists (select 1 from jsonb_object_keys(s) k where k not in ('heading', 'body'))
       or jsonb_typeof(s -> 'heading') <> 'string'
       or (s ? 'body' and jsonb_typeof(s -> 'body') not in ('string', 'null'))
       or length(btrim(s ->> 'heading')) not between 1 and 100
       or length(coalesce(s ->> 'body', '')) > 1000 then
      raise exception 'Each section needs a heading (up to 100 characters) and a body of up to 1,000 characters'
        using errcode = 'check_violation';
    end if;
    cleaned := cleaned || jsonb_build_array(jsonb_build_object(
      'heading', btrim(s ->> 'heading'),
      'body', coalesce(s ->> 'body', '')
    ));
  end loop;
  new.sections := cleaned;
  if length(public.status_template_summary(new.sections)) > 2000 then
    raise exception 'A status template''s sections must fit a status update (2,000 characters)'
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

