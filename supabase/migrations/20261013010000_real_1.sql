-- Invoker guard: the token is always the database's (never a client's); the owner, token, and creation
-- time never change; a revoked address stays revoked and unchanged; the default project is one the
-- person can add tasks to (Editor+) when they set it (post_email_forward checks again on every email).
create or replace function public.guard_email_forwarding_address()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if public.is_client_role() then
      new.profile_id := auth.uid();
    end if;
    new.token := left(public.inbound_random_hex(), 40);
    new.created_at := now();
    new.revoked_at := null;
  else
    if new.profile_id <> old.profile_id or new.token <> old.token or new.created_at <> old.created_at then
      raise exception 'A forwarding address can''t be moved' using errcode = 'insufficient_privilege';
    end if;
    if old.revoked_at is not null then
      raise exception 'This forwarding address was replaced' using errcode = 'check_violation';
    end if;
    if new.revoked_at is not null then
      new.revoked_at := now();
    end if;
  end if;
  if new.default_project_id is not null
     and (tg_op = 'INSERT' or new.default_project_id is distinct from old.default_project_id)
     and public.is_client_role()
     and not public.has_project_role(new.default_project_id, 'editor') then
    raise exception 'Choose a project you can add tasks to' using errcode = 'insufficient_privilege';
  end if;
  return new;
end;
$$;

