-- At send time an invite email is also dropped when its pending invite was cancelled or already used.
select public.alhc_patch_function('public.invite_email_block_reason(uuid)'::regprocedure,
  $old$    when o.created_at < now() - interval '7 days' then 'Not sent: more than a week late'$old$,
  $new$    when o.created_at < now() - interval '7 days' then 'Not sent: more than a week late'
    when o.payload ? 'pending_id' and exists (
      select 1 from public.pending_memberships pm
      where pm.id::text = o.payload ->> 'pending_id' and pm.applied_at is not null
    ) then 'Not sent: they already joined'
    when o.payload ? 'pending_id' and exists (
      select 1 from public.pending_memberships pm
      where pm.id::text = o.payload ->> 'pending_id' and pm.deleted_at is not null
    ) then 'Not sent: the invite was canceled'$new$
);

-- Who reads invite emails: workspace invites → workspace admins (as before); a project / portfolio /
-- team invite names that target, so only the people who manage that invite see it.
alter policy email_outbox_select_viewer on public.email_outbox
  using (
    (email_outbox.task_id is not null and (select public.has_task_role(email_outbox.task_id, 'viewer')))
    or (
      email_outbox.task_id is null and email_outbox.payload ->> 'kind' = 'invite'
      and not (email_outbox.payload ? 'pending_id')
      and (select public.is_workspace_admin())
    )
    or (
      email_outbox.task_id is null and email_outbox.payload ->> 'kind' = 'invite'
      and email_outbox.payload ? 'pending_id'
      and (select public.can_manage_pending_invite(email_outbox.payload ->> 'pending_id'))
    )
  );

