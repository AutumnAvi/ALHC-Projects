-- ALHC Projects — Phase: Real features 1 (invites and email-in).
-- ROADMAP.md section 0 listed what still pretended; this makes three of those real in the database (the
-- other two, team preselect and Home's inline task row, are UI only):
--
--   Invites by email for projects, portfolios, and teams. "Add someone by email" already left a
--     pending invite (pending_memberships) for an allowlisted address that hadn't signed in, but an
--     address outside the workspace was refused and nobody was told about a pending invite. Now:
--     a workspace admin's invite puts a new address on the allowlist first (allowlist_for_invite →
--     invite_to_workspace in quiet mode, so the one email is the invite below); anyone else still needs
--     a workspace admin (the error says so). Every new pending invite queues an invite email through the
--     existing outbox (kind invite + pending_id: who invited them, to what, a sign-up link that lands on
--     the target after the email is confirmed) — never to someone who already signed in, and at most 3 an
--     hour / 6 a day to one address. Resend = setting pending_memberships.resent_at (column
--     grant, the existing managers-only update policy, at most every 10 minutes), which queues the email
--     again. The send-time check (invite_email_block_reason) also refuses an invite that was cancelled
--     or already used. Those emails name a project, portfolio, or team, so the outbox policy shows them
--     only to the people who manage that invite (can_manage_pending_invite) — never to workspace admins
--     as such (their branch now covers only workspace invites). Joining on first sign-in is unchanged
--     (apply_pending_memberships).
--   Attachment questions on forms. A public submitter's files go straight to the private
--     task-attachments bucket at <key>/<form id>/<uuid>-<name>, where <key> is a random id the browser
--     picks for this response; submit_form makes that key the new task's id, so the files already sit
--     in the task's attachment folder (task_attachments' path check and every existing Storage read
--     policy apply unchanged) and records them (task_attachments.source = 'form'; the listed name keeps
--     the stored file's extension). Anonymous uploads are allowed by one Storage insert policy for anon
--     whose check is alhc_storage.form_upload_allowed(name) — a SECURITY DEFINER yes / no in a schema the
--     API doesn't expose, so anon can't call it as an RPC (the form is open and has a file question, the
--     key isn't a task yet, the file type is on the list, at most 10 files per response, 100 uploads /
--     500 MB per form per 10 minutes, 1,000 files / 5 GB of unsubmitted uploads a day). anon still reads
--     nothing (no Storage select policy), task readers see a form upload only once it is one of the
--     task's attachments (the select policy is narrowed for <key>/<form>/<file> objects), the cron route
--     removes unsubmitted uploads after a day (list_stale_form_uploads, service_role), and the bucket's
--     25 MB limit applies. validate_form / normalize_form_answer / form_answer_text / submit_form gain
--     the 'attachment' type by asserted patches (submit_form keeps its signature).
--   Forward emails to create tasks. Each person gets one private forwarding address token
--     (email_forwarding_addresses: own rows only, generated by the database, rotatable — a rotated
--     token stops at once) and a default project (Editor+, else My tasks). The inbound email route
--     (the verified Resend webhook, service role) calls post_email_forward() for f-<token>@<reply
--     domain>: the sender must be the token's person (never the From header alone: the token is the
--     secret, the route also checks SPF / DKIM / DMARC), still allowlisted; the task is created as that
--     person (subject = name, body = description, assigned to them) in the default project while
--     they're still an Editor there, else as their private task. attach_forwarded_file() records each
--     attachment the route copied into the task's folder. Every attempt is logged in email_forwards
--     (the person sees their own; never a body or an address).
--
-- New client surface: none in public. alhc_storage.form_upload_allowed is executable by anon only for the
-- Storage policy (its schema isn't exposed through the API, so anon's public RPCs are still the three
-- pinned in suites 50, 60, zz06, zz07). post_email_forward, attach_forwarded_file, and
-- list_stale_form_uploads are service_role only; log_email_forward, queue_pending_invite_email, and the
-- trigger functions are revoked from every client role; everything else is invoker. fire_rules, notify_with, notify_message, and add_story are untouched (their import and
-- copy checks included). Additive: the release still on main keeps working once this is applied — its
-- invite flows work as before (they just also email), it never offers attachment questions or
-- forwarding, and its outbox reads see the same workspace-invite rows. The grant on
-- email_forwarding_addresses is the last statement: the app treats this release's database features
-- as present only once that table is readable. No statement here needs a row- or object-removal
-- keyword, so there is no tail section.

create or replace function public.alhc_patch_function(target regprocedure, variadic edits text[])
returns void
language plpgsql
set search_path = ''
as $$
declare
  def text := pg_get_functiondef(target);
  hits integer;
begin
  if coalesce(array_length(edits, 1), 0) = 0 or array_length(edits, 1) % 2 <> 0 then
    raise exception 'alhc_patch_function(%): pass (old, new) text pairs', target;
  end if;
  for i in 1 .. array_length(edits, 1) / 2 loop
    if coalesce(edits[2 * i - 1], '') = '' then
      raise exception 'alhc_patch_function(%): edit % has no text to replace', target, i;
    end if;
    hits := (length(def) - length(replace(def, edits[2 * i - 1], ''))) / length(edits[2 * i - 1]);
    if hits <> 1 then
      raise exception 'alhc_patch_function(%): edit % matched % times (expected exactly once)', target, i, hits;
    end if;
    def := replace(def, edits[2 * i - 1], edits[2 * i]);
  end loop;
  execute def;
end;
$$;

revoke all on function public.alhc_patch_function(regprocedure, text[]) from public, anon, authenticated;

