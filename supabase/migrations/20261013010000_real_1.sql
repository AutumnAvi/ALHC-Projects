-- A forwarded email becomes a task (the inbound email route, service role only). The token is the
-- secret; the sender must also be its person's own address, and the route must have seen it pass
-- DMARC (sender_verified; otherwise it's logged as not_authenticated so the person can see why); they
-- must still be allowlisted. The task is
-- theirs (created as them, assigned to them): in their default project while they're still an Editor+
-- there (archived projects cap everyone at Viewer), else their private My tasks task. Subject = name
-- ("Fwd:" / "Re:" prefixes dropped), body = description. One task per provider email id.
create or replace function public.post_email_forward(
  forward_token text, sender_email text, sender_verified boolean, email_subject text, email_body text,
  provider_email_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  addr public.email_forwarding_addresses;
  person public.profiles;
  existing public.email_forwards;
  sender text := lower(btrim(coalesce(sender_email, '')));
  provider text := nullif(btrim(coalesce(provider_email_id, '')), '');
  task_title text;
  task_notes text;
  project uuid;
  first_section uuid;
  previous_sub text;
  new_task uuid;
  forward_id uuid;
begin
  if provider is not null then
    perform pg_advisory_xact_lock(hashtextextended('alhc.email_forward:' || provider, 0));
    select * into existing from public.email_forwards f
    where f.provider_id = left(provider, 200) and f.status = 'created';
    if found then
      return jsonb_build_object('ok', true, 'status', 'duplicate', 'task_id', existing.task_id, 'forward_id', existing.id);
    end if;
  end if;

  if coalesce(forward_token, '') !~ '^[0-9a-f]{40}$' then
    perform public.log_email_forward(provider, null, null, null, null, 'rejected', 'unknown_token');
    return jsonb_build_object('ok', false, 'status', 'rejected', 'reason', 'unknown_token');
  end if;
  select * into addr from public.email_forwarding_addresses a where a.token = forward_token;
  if not found then
    perform public.log_email_forward(provider, null, null, null, null, 'rejected', 'unknown_token');
    return jsonb_build_object('ok', false, 'status', 'rejected', 'reason', 'unknown_token');
  end if;
  if addr.revoked_at is not null then
    perform public.log_email_forward(provider, addr.id, addr.profile_id, null, null, 'rejected', 'rotated');
    return jsonb_build_object('ok', false, 'status', 'rejected', 'reason', 'rotated');
  end if;

  select * into person from public.profiles p where p.id = addr.profile_id;
  if not found or sender = '' or sender is distinct from lower(person.email) then
    perform public.log_email_forward(provider, addr.id, addr.profile_id, null, null, 'rejected', 'sender_mismatch');
    return jsonb_build_object('ok', false, 'status', 'rejected', 'reason', 'sender_mismatch');
  end if;
  if sender_verified is not true then
    perform public.log_email_forward(provider, addr.id, person.id, null, null, 'rejected', 'not_authenticated');
    return jsonb_build_object('ok', false, 'status', 'rejected', 'reason', 'not_authenticated');
  end if;
  if not public.profile_is_allowlisted(person.id) then
    perform public.log_email_forward(provider, addr.id, person.id, null, null, 'rejected', 'no_access');
    return jsonb_build_object('ok', false, 'status', 'rejected', 'reason', 'no_access');
  end if;

  if addr.default_project_id is not null
     and exists (
       select 1 from public.projects p
       where p.id = addr.default_project_id and p.deleted_at is null and p.archived_at is null
     )
     and public.project_role_rank(public.profile_project_role(person.id, addr.default_project_id))
       >= public.project_role_rank('editor') then
    project := addr.default_project_id;
  end if;

  task_title := btrim(regexp_replace(coalesce(email_subject, ''), '^\s*((re|fwd?|fw)\s*:\s*)+', '', 'i'));
  task_title := left(coalesce(nullif(task_title, ''), 'Forwarded email'), 500);
  task_notes := nullif(left(btrim(coalesce(email_body, ''), E' \t\r\n'), 20000), '');

  begin
    previous_sub := current_setting('request.jwt.claim.sub', true);
    perform set_config('request.jwt.claim.sub', person.id::text, true);
    if project is not null then
      select s.id into first_section from public.sections s
      where s.project_id = project and s.deleted_at is null
      order by s.sort_order, s.created_at limit 1;
      insert into public.tasks (home_project_id, title, notes, assignee_id, source, created_by)
      values (project, task_title, task_notes, person.id, 'manual', person.id)
      returning id into new_task;
      if first_section is not null then
        update public.task_projects set section_id = first_section
        where task_id = new_task and project_id = project and deleted_at is null;
      end if;
    else
      insert into public.tasks (title, notes, assignee_id, source, created_by)
      values (task_title, task_notes, person.id, 'manual', person.id)
      returning id into new_task;
    end if;
    -- The activity says it came in by email ("created this task by email").
    update public.task_stories set data = data || '{"via": "email"}'::jsonb
    where task_id = new_task and kind = 'created';
    perform set_config('request.jwt.claim.sub', coalesce(previous_sub, ''), true);
  exception when others then
    forward_id := public.log_email_forward(provider, addr.id, person.id, null, null, 'rejected', 'failed');
    return jsonb_build_object('ok', false, 'status', 'rejected', 'reason', 'failed');
  end;

  forward_id := public.log_email_forward(
    provider, addr.id, person.id, new_task, project, 'created',
    case when addr.default_project_id is not null and project is null then 'project_unavailable' end
  );
  return jsonb_build_object(
    'ok', true, 'status', 'created', 'task_id', new_task, 'project_id', project, 'forward_id', forward_id
  );
end;
$$;

