-- May an anonymous form submitter upload this object to task-attachments? The path is
-- <key>/<form id>/<uuid>-<safe name>: the form is live, accepting, in an active project, and has an
-- attachment question; <key> is not a task yet (submit_form makes it the response's task, so nobody can
-- put files in an existing task's folder); the type is on the list; at most 10 files under one key, 100
-- uploads and 500 MB to one form in 10 minutes, and 1,000 files / 5 GB of not-yet-submitted uploads in
-- the whole bucket in a day (the cron route removes unsubmitted ones after a day,
-- list_stale_form_uploads). Each file: the bucket's 25 MB limit. A yes / no only.
create or replace function alhc_storage.form_upload_allowed(object_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  parts text[] := string_to_array(coalesce(object_name, ''), '/');
  uuid_pattern constant text := '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$';
  recent_count bigint;
  recent_bytes bigint;
begin
  if cardinality(parts) <> 3
     or parts[1] !~ uuid_pattern
     or parts[2] !~ uuid_pattern
     or parts[3] !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}-[A-Za-z0-9._-]{1,100}$'
     or not public.form_upload_extension_ok(parts[3]) then
    return false;
  end if;
  if not exists (
    select 1 from public.forms f
    join public.projects p on p.id = f.project_id and p.deleted_at is null and p.archived_at is null
    where f.id = parts[2]::uuid and f.deleted_at is null and f.accepting_responses
      and f.questions @> '[{"type": "attachment"}]'::jsonb
  ) then
    return false;
  end if;
  if exists (select 1 from public.tasks t where t.id = parts[1]::uuid) then
    return false;
  end if;
  if (
    select count(*) from storage.objects o
    where o.bucket_id = 'task-attachments' and o.name like parts[1] || '/%'
  ) >= 10 then
    return false;
  end if;
  select count(*), coalesce(sum(public.form_upload_size(o.metadata)), 0) into recent_count, recent_bytes
  from storage.objects o
  where o.bucket_id = 'task-attachments' and split_part(o.name, '/', 2) = parts[2]
    and o.created_at > now() - interval '10 minutes';
  if recent_count >= 100 or recent_bytes >= 500 * 1024 * 1024 then
    return false;
  end if;
  select count(*), coalesce(sum(public.form_upload_size(o.metadata)), 0) into recent_count, recent_bytes
  from storage.objects o
  where o.bucket_id = 'task-attachments' and o.created_at > now() - interval '1 day'
    and o.name ~ '^[0-9a-f-]{36}/[0-9a-f-]{36}/[^/]+$'
    and not exists (select 1 from public.task_attachments a where a.storage_path = o.name);
  if recent_count >= 1000 or recent_bytes >= 5::bigint * 1024 * 1024 * 1024 then
    return false;
  end if;
  return true;
end;
$$;

