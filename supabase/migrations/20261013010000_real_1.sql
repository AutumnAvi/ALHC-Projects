-- One attachment of a forwarded email, after the route copied it into the task's folder: within an
-- hour of the forward, at most 10, recorded as the person (their story) with source email.
create or replace function public.attach_forwarded_file(
  target_forward uuid, file_path text, file_name text, file_type text, file_size bigint
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  f public.email_forwards;
  previous_sub text;
  attachment uuid;
begin
  select * into f from public.email_forwards x where x.id = target_forward and x.status = 'created' for update;
  if not found or f.task_id is null or f.profile_id is null or f.created_at < now() - interval '1 hour' then
    raise exception 'Forwarded email not found' using errcode = 'no_data_found';
  end if;
  if f.attachments >= 10 then
    raise exception 'At most 10 attachments per email' using errcode = 'check_violation';
  end if;
  if file_path is null or file_path not like f.task_id::text || '/%' or position('..' in file_path) > 0 then
    raise exception 'Invalid attachment path' using errcode = 'check_violation';
  end if;
  previous_sub := current_setting('request.jwt.claim.sub', true);
  perform set_config('request.jwt.claim.sub', f.profile_id::text, true);
  insert into public.task_attachments (task_id, storage_path, file_name, content_type, size_bytes, uploaded_by, source)
  values (
    f.task_id, file_path,
    left(coalesce(nullif(btrim(file_name), ''), 'attachment'), 255),
    nullif(left(btrim(coalesce(file_type, '')), 255), ''),
    greatest(coalesce(file_size, 0), 0),
    f.profile_id,
    'email'
  )
  returning id into attachment;
  perform set_config('request.jwt.claim.sub', coalesce(previous_sub, ''), true);
  update public.email_forwards set attachments = attachments + 1 where id = f.id;
  return attachment;
end;
$$;

revoke all on function public.attach_forwarded_file(uuid, text, text, text, bigint) from public, anon, authenticated;
grant execute on function public.attach_forwarded_file(uuid, text, text, text, bigint) to service_role;

