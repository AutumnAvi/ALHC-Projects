-- invite_to_workspace in quiet mode (alhc.invite_quiet = on, transaction-local, set only by
-- allowlist_for_invite below) adds or restores the address without the generic workspace email: the
-- project / portfolio / team invite that follows sends the one email.
select public.alhc_patch_function('public.invite_to_workspace(text)'::regprocedure,
  $old$  if not signed_in then
    email_id := public.queue_workspace_invite_email(address, ws);
  end if;$old$,
  $new$  -- A project, portfolio, or team invite that allowlists the address (Real features 1) runs this in
  -- quiet mode and sends its own email instead.
  if not signed_in and coalesce(current_setting('alhc.invite_quiet', true), '') <> 'on' then
    email_id := public.queue_workspace_invite_email(address, ws);
  end if;$new$
);

-- Is the address on the workspace allowlist — after adding it when the caller is a workspace admin?
-- Invoker: the allowlist is readable by everyone allowlisted, and adding goes through
-- invite_to_workspace (workspace admins only). Anyone else gets false and the caller's own error. Only a
-- brand-new address is added: someone removed from the workspace comes back only through Admin console
-- → Add back, never as a side effect of a project, portfolio, or team invite (add_team_to_project loops
-- over team members, removed ones included).
create or replace function public.allowlist_for_invite(address text, ws uuid)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  if exists (select 1 from public.allowed_emails a where a.email = address and a.removed_at is null) then
    return true;
  end if;
  if not public.is_email(address) or ws is null or not public.is_workspace_admin(ws) then
    return false;
  end if;
  if exists (select 1 from public.allowed_emails a where a.email = address) then
    raise exception '% was removed from the workspace', address
      using errcode = 'check_violation', hint = 'Add them back from the Admin console first.';
  end if;
  perform set_config('alhc.invite_quiet', 'on', true);
  perform public.invite_to_workspace(address);
  perform set_config('alhc.invite_quiet', '', true);
  return exists (select 1 from public.allowed_emails a where a.email = address and a.removed_at is null);
end;
$$;

select public.alhc_revoke_anon_execute(array['allowlist_for_invite(text,uuid)']);
grant execute on function public.allowlist_for_invite(text, uuid) to authenticated;

