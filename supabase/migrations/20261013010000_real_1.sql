-- A new address for the caller: the old one stops at once (mail to it is logged as rotated). Keeps the
-- default project while they can still add tasks to it. Invoker.
create or replace function public.rotate_forwarding_address()
returns public.email_forwarding_addresses
language plpgsql
set search_path = ''
as $$
declare
  previous public.email_forwarding_addresses;
  r public.email_forwarding_addresses;
begin
  if not public.is_allowlisted() then
    raise exception 'Not allowed' using errcode = 'insufficient_privilege';
  end if;
  update public.email_forwarding_addresses a set revoked_at = now()
  where a.profile_id = auth.uid() and a.revoked_at is null
  returning * into previous;
  insert into public.email_forwarding_addresses (profile_id, default_project_id)
  values (
    auth.uid(),
    case when previous.default_project_id is not null and public.has_project_role(previous.default_project_id, 'editor')
      then previous.default_project_id end
  )
  returning * into r;
  return r;
end;
$$;

