-- Resend: a manager sets resent_at (the update policy already limits that to project / portfolio
-- Admins+ and team managers). The guard stamps the time, refuses closed invites (as before), and allows
-- one email every 10 minutes per invite; client inserts never carry it.
select public.alhc_patch_function('public.guard_pending_membership()'::regprocedure,
  $old$      new.deleted_at := null;$old$,
  $new$      new.deleted_at := null;
      new.resent_at := null;
      -- Someone who already signed in is added directly (add_team_member does), never invited by email.
      if exists (select 1 from public.profiles p where lower(p.email) = new.email and p.joined_at is not null) then
        raise exception '% has already signed in. Add them as a member instead.', new.email using errcode = 'check_violation';
      end if;$new$,
  $old$    if new.applied_at is distinct from old.applied_at or new.applied_profile_id is distinct from old.applied_profile_id then
      raise exception 'Invites apply on first sign-in' using errcode = 'insufficient_privilege';
    end if;$old$,
  $new$    if new.applied_at is distinct from old.applied_at or new.applied_profile_id is distinct from old.applied_profile_id then
      raise exception 'Invites apply on first sign-in' using errcode = 'insufficient_privilege';
    end if;
    -- Resend (Real features 1): the time is ours, once every 10 minutes, and only to an address that is
    -- still in the workspace.
    if new.resent_at is distinct from old.resent_at then
      if new.deleted_at is not null then
        raise exception 'This invite was already used or canceled' using errcode = 'check_violation';
      end if;
      if coalesce(old.resent_at, old.created_at) > now() - interval '10 minutes' then
        raise exception 'An invite was just sent to %', old.email
          using errcode = 'check_violation', hint = 'Wait a few minutes before sending another.';
      end if;
      if not exists (select 1 from public.allowed_emails a where a.email = old.email and a.removed_at is null) then
        raise exception '% isn''t in this workspace anymore', old.email using errcode = 'check_violation';
      end if;
      new.resent_at := now();
    end if;$new$
);

