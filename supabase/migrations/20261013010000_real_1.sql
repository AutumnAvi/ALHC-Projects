-- The invite email for one open pending invite: who invited them (a name, never an address), what to
-- (the project / portfolio / team name and its path), the role, and the workspace. email.ts renders it
-- with a sign-up link for the recipient's address that lands on the target. Internal (definer, revoked).
create or replace function public.queue_pending_invite_email(target_invite uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  pm public.pending_memberships;
  inviter text;
  ws_name text;
  target_kind text;
  target_name text;
  target_path text;
begin
  select * into pm from public.pending_memberships m where m.id = target_invite;
  if not found or pm.applied_at is not null or pm.deleted_at is not null then
    return null;
  end if;
  if not exists (select 1 from public.allowed_emails a where a.email = pm.email and a.removed_at is null) then
    return null;
  end if;
  -- Already signed in: nothing to sign up for (their invite applies on their next sign-in).
  if exists (select 1 from public.profiles p where lower(p.email) = pm.email and p.joined_at is not null) then
    return null;
  end if;
  -- No inbox gets more than 3 invite emails an hour or 6 a day from this workspace, whoever sends them
  -- (the invites themselves still wait for the first sign-in). Serialized per address.
  perform pg_advisory_xact_lock(hashtextextended('alhc.invite_email:' || pm.email, 0));
  if (
    select count(*) from public.email_outbox o
    where o.to_email = pm.email and o.task_id is null and o.payload ->> 'kind' = 'invite'
      and o.created_at > now() - interval '1 hour'
  ) >= 3 or (
    select count(*) from public.email_outbox o
    where o.to_email = pm.email and o.task_id is null and o.payload ->> 'kind' = 'invite'
      and o.created_at > now() - interval '1 day'
  ) >= 6 then
    return null;
  end if;
  if pm.project_id is not null then
    target_kind := 'project';
    select p.name into target_name from public.projects p where p.id = pm.project_id and p.deleted_at is null;
    target_path := '/projects/' || pm.project_id::text;
  elsif pm.portfolio_id is not null then
    target_kind := 'portfolio';
    select p.name into target_name from public.portfolios p where p.id = pm.portfolio_id and p.deleted_at is null;
    target_path := '/portfolios/' || pm.portfolio_id::text;
  else
    target_kind := 'team';
    select t.name into target_name from public.teams t where t.id = pm.team_id and t.deleted_at is null;
    target_path := '/teams/' || pm.team_id::text;
  end if;
  if target_name is null then
    return null;
  end if;
  select nullif(btrim(p.full_name), '') into inviter
  from public.profiles p where p.id = coalesce(auth.uid(), pm.created_by);
  inviter := coalesce(inviter, 'A teammate');
  select w.name into ws_name from public.workspaces w where w.id = pm.workspace_id;
  return public.enqueue_email(
    pm.email,
    'custom',
    inviter || ' invited you to ' || target_name,
    jsonb_build_object(
      'kind', 'invite',
      'pending_id', pm.id,
      'target_kind', target_kind,
      'target_name', target_name,
      'target_path', target_path,
      'role', pm.role,
      'inviter_name', inviter,
      'workspace_name', coalesce(ws_name, 'ALHC Projects'),
      'message', inviter || ' invited you to the ' || target_kind || ' “' || target_name
        || '” on ALHC Projects. Sign up with this address to get started.'
    ),
    null
  );
end;
$$;

revoke all on function public.queue_pending_invite_email(uuid) from public, anon, authenticated;

