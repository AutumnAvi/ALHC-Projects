-- The name a form file is listed under: the name the submitter's browser gave, without control
-- characters, when it ends in the same extension as the stored file (the type the upload check allowed);
-- otherwise the stored name. So nobody can list an allowed .pdf upload as "Invoice.exe".
create or replace function public.form_upload_display_name(given text, object_name text)
returns text
language sql
immutable
set search_path = ''
as $$
  select left(case
    when lower(substring(btrim(regexp_replace(coalesce(given, ''), '[[:cntrl:]]', '', 'g')) from '\.([A-Za-z0-9]{1,8})$'))
       = lower(substring(coalesce(object_name, '') from '\.([A-Za-z0-9]{1,8})$'))
      then btrim(regexp_replace(given, '[[:cntrl:]]', '', 'g'))
    else public.form_upload_file_name(object_name)
  end, 255);
$$;

revoke all on function public.form_upload_display_name(text, text) from public, anon, authenticated;

